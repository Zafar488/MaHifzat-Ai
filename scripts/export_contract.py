"""Generate frontend clinical types from the authoritative Pydantic contract."""
from pathlib import Path
import sys
import json
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.schemas.clinical import ClinicalInput

def render():
    schema = ClinicalInput.model_json_schema()
    lines = ["// Generated by scripts/export_contract.py. Do not hand-edit.", "export interface ClinicalInput {"]
    for name, spec in schema["properties"].items():
        choices = spec.get("anyOf", [spec])
        types = []
        for choice in choices:
            if "enum" in choice:
                types.append(" | ".join(json.dumps(v) for v in choice["enum"]))
            else:
                types.append({"number": "number", "integer": "number", "boolean": "boolean", "string": "string", "null": "null"}[choice["type"]])
        lines.append("  " + name + "?: " + " | ".join(types))
    lines += ["}", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    folder = ROOT / "docs/contracts"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "clinical.generated.ts").write_text(render(), encoding="utf-8")
